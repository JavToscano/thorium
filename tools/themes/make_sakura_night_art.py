"""Draws the artwork of the "Sakura Night" theme: background layers and tab icons.

Everything is original and generated by code (no third-party art). Output goes to
app/src/main/assets/themes/sakura-night/{images,icons}.

Usage: python3 tools/themes/make_sakura_night_art.py
Needs Pillow and numpy.
"""
